class EthlambdaMinimal < Formula
  desc "Beacon Chain and Lean Chain client in Rust, without embedded ethrex"
  homepage "https://docs.ethlambda.xyz/"
  url "https://github.com/lambdaclass/ethlambda/archive/refs/tags/v1.0.0.tar.gz"
  sha256 "07dbaba9fa48806cbcdc2bc32cc208c9355bb65ca60714fa1866ed8d9f2eadd3"
  license "MIT"

  livecheck do
    url :stable
    regex(/^v([0-9]+\.[0-9]+\.[0-9]+)$/i)
  end

  # The bottle is added with the first release that ships
  # `ethlambda-minimal-macos-aarch64`, repackaged from that asset (ethlambda's
  # RELEASE.md, step 6), next to the `ethlambda` bottle on the same tap release.

  depends_on "rustup" => :build

  # RocksDB's bindings are generated by bindgen, which needs libclang. macOS
  # ships it with the Command Line Tools; Linux takes it from `llvm`.
  uses_from_macos "llvm" => :build

  # Both formulas install a binary named `ethlambda`: this one without ethrex,
  # `ethlambda` with it.
  conflicts_with "ethlambda", because: "both install an `ethlambda` binary"

  def install
    system "rustup", "toolchain", "install", "1.97.1"
    # `--version` reports the git branch as its release channel, and a tarball
    # has no checkout to read one from. vergen takes this override instead.
    ENV["VERGEN_GIT_BRANCH"] = "stable"
    # No features: the build without ethrex (`ethlambda-minimal-<platform>` in
    # ethlambda's releases).
    system "cargo", "install", *std_cargo_args(path: "bin/ethlambda")
  end

  test do
    assert_match "ethlambda/v#{version}-", shell_output("#{bin}/ethlambda --version")
    # Only a build with ethrex embedded takes the `--ethrex.*` flags.
    refute_match "--ethrex.", shell_output("#{bin}/ethlambda beacon --help")
  end
end
